/*
 * Build content.js from the source data in content/.
 *
 *   content/meta.json          version, stageNames, wordPool, knowledge,
 *                              roadmap, review, and levelOrder (level ids, in
 *                              play order)
 *   content/levels/<id>.json   one level object each
 *
 * Output is a plain `window.GREPPO = {...}` script so the game loads it with no
 * network — works opened from disk, on GitHub Pages and inside the artifact.
 * content.js is GENERATED; edit the JSON, not content.js. Run: npm run build
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const readJSON = (p) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));

const meta = readJSON('content/meta.json');
/* Mini-articles shown before a lesson introduces new commands (keyed by lesson id). */
const articles = existsSync(resolve(root, 'content/articles.json')) ? readJSON('content/articles.json') : {};
if (!Array.isArray(meta.levelOrder) || !meta.levelOrder.length) {
  console.error('FAIL: meta.json needs a non-empty levelOrder array');
  process.exit(1);
}

const levels = meta.levelOrder.map((id) => {
  const lv = readJSON(`content/levels/${id}.json`);
  if (lv.id !== id) { console.error(`FAIL: content/levels/${id}.json has id "${lv.id}"`); process.exit(1); }
  return lv;
});

// Assemble in a stable key order for clean diffs.
const G = {
  version: meta.version,
  stageNames: meta.stageNames,
  wordPool: meta.wordPool,
  knowledge: meta.knowledge,
  roadmap: meta.roadmap,
  review: meta.review,
  articles,
  levels,
};

const header =
  '/* AUTO-GENERATED from content/*.json by tools/build-content.mjs.\n' +
  ' * Do NOT edit this file by hand — edit the JSON under content/ and run\n' +
  ' * `npm run build`. The game loads this as window.GREPPO with no network. */\n';

writeFileSync(resolve(root, 'content.js'), header + 'window.GREPPO = ' + JSON.stringify(G, null, 2) + ';\n');
console.log(`built content.js: ${levels.length} levels from content/`);
